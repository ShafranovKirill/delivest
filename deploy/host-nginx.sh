#!/bin/sh
# Points the host nginx at this deployment's gateway container and keeps its TLS certificate.
# Run from the repository on the server: sudo ./deploy/host-nginx.sh
# Safe to run again: the working config is replaced only after `nginx -t` passes.
set -eu

cd "$(dirname "$0")/.."

env_value() {
  grep -E "^$1=" .env | tail -n 1 | cut -d= -f2- | sed -e 's/^"//' -e 's/"$//' -e "s/^'//" -e "s/'$//"
}

host_of() {
  printf '%s' "$1" | sed -E -e 's#^[a-z]+://##' -e 's#[/:].*$##'
}

[ -f .env ] || { echo ".env not found" >&2; exit 1; }

PROJECT=$(env_value COMPOSE_PROJECT_NAME)
PROJECT=${PROJECT:-delivest}
case "$PROJECT" in *[!a-zA-Z0-9_-]*|'') echo "invalid COMPOSE_PROJECT_NAME" >&2; exit 1;; esac
PORT=$(env_value GATEWAY_PORT)
PORT=${PORT:-8080}
CLIENT_HOST=$(host_of "$(env_value CLIENT_ORIGIN)")
SERVER_HOST=$(host_of "$(env_value PHX_HOST)")
S3_HOST=$(host_of "$(env_value S3_PUBLIC_HOST)")
EMAIL=$(env_value LETSENCRYPT_EMAIL)
DOMAINS="$CLIENT_HOST $SERVER_HOST $S3_HOST"

for name in CLIENT_HOST SERVER_HOST S3_HOST; do
  eval "value=\$$name"
  [ -n "$value" ] || { echo "$name is empty, check .env" >&2; exit 1; }
done
case "$SERVER_HOST" in *[!a-zA-Z0-9.-]*|'') echo "invalid PHX_HOST" >&2; exit 1;; esac

MONITOR_DIR=/var/www/delivest-backup-status/$PROJECT
install -d -m 0750 -o root -g www-data "$MONITOR_DIR"
MONITOR_HTML=$(mktemp)
sed "s|__ADMIN_ORIGIN__|https://$SERVER_HOST|g" deploy/backup-status/index.html > "$MONITOR_HTML"
install -m 0640 -o root -g www-data "$MONITOR_HTML" "$MONITOR_DIR/index.html"
rm -f "$MONITOR_HTML"
install -m 0640 -o root -g www-data deploy/backup-status/monitor.js "$MONITOR_DIR/monitor.js"
install -m 0640 -o root -g www-data deploy/backup-status/monitor.css "$MONITOR_DIR/monitor.css"

if [ -d /etc/nginx/sites-available ]; then
  CONF=/etc/nginx/sites-available/$PROJECT.conf
  LINK=/etc/nginx/sites-enabled/$PROJECT.conf
else
  CONF=/etc/nginx/conf.d/$PROJECT.conf
  LINK=
fi

CERT_DIR=/etc/letsencrypt/live/$PROJECT

# shellcheck disable=SC2016
if ! grep -rqs 'map \$http_upgrade \$connection_upgrade' /etc/nginx; then
  cat > /etc/nginx/conf.d/connection-upgrade.conf <<'CONF'
map $http_upgrade $connection_upgrade {
    default upgrade;
    ''      close;
}
CONF
fi

cat > /etc/nginx/conf.d/delivest-access-log.conf <<'CONF'
log_format delivest_safe '$remote_addr - $remote_user [$time_local] '
                         '"$request_method $uri $server_protocol" $status $body_bytes_sent';
CONF

proxy_location() {
  cat <<CONF
    location / {
        proxy_pass http://127.0.0.1:$PORT;
        proxy_http_version 1.1;
        proxy_set_header Host \$host;
        proxy_set_header Upgrade \$http_upgrade;
        proxy_set_header Connection \$connection_upgrade;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \$scheme;
        proxy_read_timeout 120s;
        proxy_request_buffering off;
    }
CONF
}

monitor_headers() {
  cat <<'CONF'
        access_log off;
        add_header Cache-Control "no-store, max-age=0" always;
        add_header Referrer-Policy "no-referrer" always;
        add_header X-Content-Type-Options "nosniff" always;
        add_header Content-Security-Policy "default-src 'none'; script-src 'self'; style-src 'self'; connect-src 'self'; base-uri 'none'; frame-ancestors 'none'" always;
        if ($request_method != GET) { return 405; }
CONF
}

monitor_locations() {
  cat <<CONF
    location = /_backup-status/ {
        access_log off;
        rewrite ^ /_backup-status/index.html last;
    }
    location = /_backup-status/index.html {
        alias $MONITOR_DIR/index.html;
        default_type text/html;
CONF
  monitor_headers
  cat <<CONF
    }
    location = /_backup-status/monitor.js {
        alias $MONITOR_DIR/monitor.js;
        default_type text/javascript;
CONF
  monitor_headers
  cat <<CONF
    }
    location = /_backup-status/monitor.css {
        alias $MONITOR_DIR/monitor.css;
        default_type text/css;
CONF
  monitor_headers
  cat <<CONF
    }
    location = /_backup-status/heartbeat.json {
        alias $MONITOR_DIR/heartbeat.json;
        default_type application/json;
CONF
  monitor_headers
  cat <<CONF
    }
    location ~ "^/_backup-status/([0-9a-f]{64})\.json\$" {
        alias $MONITOR_DIR/\$1.json;
        default_type application/json;
CONF
  monitor_headers
  cat <<'CONF'
    }
    location /_backup-status/ {
CONF
  monitor_headers
  cat <<'CONF'
        return 404;
    }
CONF
}

write_http_conf() {
  {
    echo "# $PROJECT: generated by deploy/host-nginx.sh"
    echo "server {"
    echo "    listen 80;"
    echo "    server_name $DOMAINS;"
    echo "    client_max_body_size 20M;"
    echo "    access_log /var/log/nginx/access.log delivest_safe;"
    echo "    error_log /var/log/nginx/error.log crit;"
    monitor_locations
    proxy_location
    echo "}"
  } > "$1"
}

write_https_conf() {
  {
    echo "# $PROJECT: generated by deploy/host-nginx.sh"
    echo "server {"
    echo "    listen 443 ssl;"
    echo "    http2 on;"
    echo "    server_name $DOMAINS;"
    echo ""
    echo "    ssl_certificate $CERT_DIR/fullchain.pem;"
    echo "    ssl_certificate_key $CERT_DIR/privkey.pem;"
    [ -f /etc/letsencrypt/options-ssl-nginx.conf ] &&
      echo "    include /etc/letsencrypt/options-ssl-nginx.conf;"
    [ -f /etc/letsencrypt/ssl-dhparams.pem ] &&
      echo "    ssl_dhparam /etc/letsencrypt/ssl-dhparams.pem;"
    echo ""
    echo "    client_max_body_size 20M;"
    echo "    access_log /var/log/nginx/access.log delivest_safe;"
    echo "    error_log /var/log/nginx/error.log crit;"
    monitor_locations
    proxy_location
    echo "}"
    echo ""
    echo "server {"
    echo "    listen 80;"
    echo "    server_name $DOMAINS;"
    echo "    access_log /var/log/nginx/access.log delivest_safe;"
    echo "    error_log /var/log/nginx/error.log crit;"
    echo "    location /_backup-status/ {"
    monitor_headers
    echo "        return 301 https://\$host\$request_uri;"
    echo "    }"
    echo "    location / { return 301 https://\$host\$request_uri; }"
    echo "}"
  } > "$1"
}

install_conf() {
  [ -f "$CONF" ] && cp "$CONF" "$CONF.previous"
  cp "$1" "$CONF"
  [ -n "$LINK" ] && ln -sf "$CONF" "$LINK"

  if nginx -t 2>/dev/null; then
    systemctl reload nginx
  else
    nginx -t || true
    if [ -f "$CONF.previous" ]; then mv "$CONF.previous" "$CONF"; else rm -f "$CONF" ${LINK:+"$LINK"}; fi
    echo "nginx config is invalid, the previous one is kept" >&2
    exit 1
  fi
}

HOOK=/etc/letsencrypt/renewal-hooks/deploy/reload-nginx.sh
mkdir -p "$(dirname "$HOOK")"
printf '#!/bin/sh\nsystemctl reload nginx\n' > "$HOOK"
chmod +x "$HOOK"

TMP=$(mktemp)
trap 'rm -f "$TMP"' EXIT

if [ ! -f "$CERT_DIR/fullchain.pem" ]; then
  write_http_conf "$TMP"
  install_conf "$TMP"
fi

if [ -n "$EMAIL" ]; then
  set -- --email "$EMAIL"
else
  set -- --register-unsafely-without-email
fi

set -- certonly --nginx --non-interactive --agree-tos "$@" --keep-until-expiring --expand \
  --cert-name "$PROJECT"

for domain in $DOMAINS; do
  set -- "$@" -d "$domain"
done

if ! certbot "$@"; then
  [ -f "$CERT_DIR/fullchain.pem" ] || { echo "certbot failed, no certificate yet" >&2; exit 1; }
  echo "certbot failed, keeping the existing certificate" >&2
fi

write_https_conf "$TMP"
install_conf "$TMP"
install -m 0640 -o root -g www-data /dev/null "$MONITOR_DIR/monitor-enabled"

echo "Done: https://$CLIENT_HOST, https://$SERVER_HOST, https://$S3_HOST -> 127.0.0.1:$PORT"
